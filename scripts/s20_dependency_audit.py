#!/usr/bin/env python
"""S20 依赖锁定与补丁基线审计（离线可运行，可选联网 pip-audit）。

用法::

    python scripts/s20_dependency_audit.py            # 生成锁定 + 审计
    python scripts/s20_dependency_audit.py --json out.json
    python scripts/s20_dependency_audit.py --skip-pip-audit
    python scripts/s20_dependency_audit.py --self-test

产物
----
- ``requirements.lock.txt``：**项目依赖**精确锁定（白名单闭包，可直接部署）；
- ``requirements.env-snapshot.txt``：当前环境完整包快照（审计证据，含无关包）；
- 审计报告 JSON：锁定完整性、安全基线、锁与环境一致性、pip-audit 结果。
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / 'requirements.lock.txt'
SNAPSHOT = ROOT / 'requirements.env-snapshot.txt'

#: 项目实际依赖（顶层 + 传递闭包）；其余包属于本机环境残留，不进入部署锁定
PROJECT_PACKAGES = (
    'django', 'asgiref', 'sqlparse', 'tzdata',
    'django-cors-headers',
    'pymysql', 'cryptography', 'cffi', 'pycparser',
    'openpyxl', 'et_xmlfile',
    'pillow',
    'playwright', 'greenlet', 'pyee',
)

#: 关键包安全基线（低于该版本视为需升级）
MINIMUM_VERSIONS = {
    'django': '5.2.17',
    'pymysql': '1.1.1',
    'cryptography': '43.0.0',
    'requests': '2.32.0',
    'urllib3': '2.2.2',
    'sqlparse': '0.5.0',
    'pillow': '10.4.0',
    'playwright': '1.47.0',
}

PIN_RE = re.compile(r'^([A-Za-z0-9_.\-]+)==([^\s;#]+)$')


def parse_lock(path):
    entries = []
    for raw in path.read_text(encoding='utf-8-sig').splitlines():
        line = raw.strip().lstrip('\ufeff')
        if not line or line.startswith('#'):
            continue
        match = PIN_RE.match(line)
        if match:
            entries.append((match.group(1).lower(), match.group(2)))
    return entries


def unpinned_lines(path):
    bad = []
    for raw in path.read_text(encoding='utf-8-sig').splitlines():
        line = raw.strip().lstrip('\ufeff')
        if not line or line.startswith('#'):
            continue
        if not PIN_RE.match(line):
            bad.append(line)
    return bad


def version_tuple(text):
    base = str(text).split('+', 1)[0]
    parts = []
    for chunk in re.split(r'[.\-]', base):
        if chunk.isdigit():
            parts.append(int(chunk))
        else:
            break
    return tuple(parts)


def is_older(version, minimum):
    return version_tuple(version) < version_tuple(minimum)


def is_local_version(version):
    return '+' in str(version)


def normalize(name):
    """PEP 503 名称规范化：et-xmlfile 与 et_xmlfile 视为同一包。"""
    return re.sub(r'[-_.]+', '-', str(name)).lower()


def installed_versions():
    """返回 {规范化名称: (原始名称, 版本)}。"""
    result = {}
    try:
        output = subprocess.run(  # noqa: S603 - 固定参数
            [sys.executable, '-m', 'pip', 'freeze'],
            capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return result
    for line in (output.stdout or '').splitlines():
        match = PIN_RE.match(line.strip())
        if match:
            result[normalize(match.group(1))] = (match.group(1), match.group(2))
    return result


def write_files():
    """生成项目锁定与完整环境快照，返回 (locked_entries, missing, snapshot_count)。"""
    installed = installed_versions()
    if not installed:
        raise SystemExit('无法读取 pip freeze，环境异常')

    snapshot_lines = ['# SMASS environment snapshot (pip freeze, audit evidence only)']
    snapshot_lines += ['{}=={}'.format(name, version)
                       for name, version in sorted(installed.values())]
    SNAPSHOT.write_text('\n'.join(snapshot_lines) + '\n', encoding='utf-8')

    locked = []
    missing = []
    for name in PROJECT_PACKAGES:
        found = installed.get(normalize(name))
        if found is None:
            missing.append(name)
            continue
        locked.append(found)
    if missing:
        raise SystemExit('项目依赖缺失：{}'.format(missing))

    lock_lines = ['# SMASS project dependency lock (generated by scripts/s20_dependency_audit.py)',
                  '# ASCII only: pip-audit decodes requirement files with the platform locale.']
    lock_lines += ['{}=={}'.format(name, version) for name, version in locked]
    LOCK.write_text('\n'.join(lock_lines) + '\n', encoding='utf-8')
    return locked, missing, len(installed)


def run_pip_audit(requirements, timeout=900):
    try:
        completed = subprocess.run(  # noqa: S603 - 固定参数
            [sys.executable, '-m', 'pip_audit', '-r', str(requirements),
             '--format', 'json', '--progress-spinner', 'off'],
            capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError:
        return 'unavailable', {'reason': 'pip-audit 未安装'}
    except subprocess.SubprocessError as exc:
        return 'error', {'reason': str(exc)}

    if completed.returncode != 0 and not completed.stdout.strip():
        return 'error', {'reason': (completed.stderr or '').strip()[-2000:]}
    try:
        payload = json.loads(completed.stdout)
    except json.JSONDecodeError:
        return 'error', {'reason': 'pip-audit 输出非 JSON',
                         'stderr': (completed.stderr or '').strip()[-1000:]}
    return 'ok', payload


def audit(skip_pip_audit=False, regenerate=True):
    report = {'checks': [], 'ok': True}
    if regenerate:
        locked, missing, snapshot_count = write_files()
        report['lock_file'] = str(LOCK)
        report['snapshot_file'] = str(SNAPSHOT)
        report['environment_packages'] = snapshot_count
        report['locked_packages'] = len(locked)
        report['excluded_environment_packages'] = snapshot_count - len(locked)
    else:
        locked = parse_lock(LOCK)
        report['lock_file'] = str(LOCK)
        report['locked_packages'] = len(locked)

    unpinned = unpinned_lines(LOCK)
    report['checks'].append({
        'name': 'all-pinned',
        'status': 'pass' if not unpinned else 'fail',
        'detail': '全部精确锁定' if not unpinned else '未锁定：{}'.format(unpinned[:5]),
    })
    if unpinned:
        report['ok'] = False

    local = [name for name, version in locked if is_local_version(version)]
    report['checks'].append({
        'name': 'reproducible',
        'status': 'pass' if not local else 'warn',
        'detail': '无本地版本后缀' if not local else '本地版本：{}'.format(local),
    })

    below = []
    for name, version in locked:
        minimum = MINIMUM_VERSIONS.get(name)
        if minimum and is_older(version, minimum):
            below.append({'package': name, 'installed': version, 'minimum': minimum})
    report['checks'].append({
        'name': 'security-baseline',
        'status': 'pass' if not below else 'fail',
        'detail': '关键包均达到基线' if not below else below,
    })
    if below:
        report['ok'] = False

    installed = installed_versions()
    drift = []
    for name, version in locked:
        found = installed.get(normalize(name))
        actual = None if found is None else found[1]
        if actual is None:
            drift.append({'package': name, 'lock': version, 'installed': None})
        elif actual != version:
            drift.append({'package': name, 'lock': version, 'installed': actual})
    report['checks'].append({
        'name': 'lock-matches-env',
        'status': 'pass' if not drift else 'warn',
        'detail': '锁与环境一致' if not drift else drift[:10],
    })

    if skip_pip_audit:
        report['checks'].append({'name': 'pip-audit', 'status': 'skip',
                                 'detail': '按参数跳过'})
    else:
        status, payload = run_pip_audit(LOCK)
        if status == 'ok':
            vulns = []
            for item in payload.get('dependencies', []):
                for vuln in item.get('vulns', []) or []:
                    vulns.append({'package': item.get('name'),
                                  'version': item.get('version'),
                                  'id': vuln.get('id'),
                                  'fix': vuln.get('fix_versions')})
            report['checks'].append({
                'name': 'pip-audit',
                'status': 'pass' if not vulns else 'fail',
                'detail': '未发现已知漏洞' if not vulns else vulns,
            })
            if vulns:
                report['ok'] = False
        else:
            report['checks'].append({'name': 'pip-audit', 'status': 'warn',
                                     'detail': payload})
    return report


def self_test():
    failures = []

    def check(condition, message):
        if not condition:
            failures.append(message)

    check(version_tuple('5.2.17') == (5, 2, 17), 'version_tuple 基本解析')
    check(version_tuple('2.12.0+cpu') == (2, 12, 0), '本地版本后缀被忽略')
    check(is_older('5.2.9', '5.2.17'), '5.2.9 < 5.2.17')
    check(not is_older('5.2.17', '5.2.17'), '相等不算旧')
    check(not is_older('5.2.18', '5.2.17'), '5.2.18 更新')
    check(is_local_version('2.12.0+cpu'), '识别本地版本')
    check(not is_local_version('5.2.17'), '普通版本不算本地')
    check(PIN_RE.match('Django==5.2.17') is not None, '精确锁定识别')
    check(PIN_RE.match('Django>=5.2.17') is None, '范围约束不算锁定')
    check('django' in PROJECT_PACKAGES, '白名单包含 django')

    for message in failures:
        print('SELF-TEST FAIL:', message)
    if not failures:
        print('SELF-TEST PASS (10 checks)')
    return 0 if not failures else 1


def main():
    parser = argparse.ArgumentParser(description='S20 依赖锁定与补丁基线审计')
    parser.add_argument('--json', dest='json_path', default='')
    parser.add_argument('--skip-pip-audit', action='store_true')
    parser.add_argument('--no-regenerate', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    report = audit(skip_pip_audit=args.skip_pip_audit,
                   regenerate=not args.no_regenerate)
    text = json.dumps(report, ensure_ascii=False, indent=2)
    if args.json_path:
        Path(args.json_path).write_text(text, encoding='utf-8')
    print(text)
    for check in report['checks']:
        detail = check['detail']
        print('[{:4}] {:22} {}'.format(
            check['status'].upper(), check['name'],
            detail if isinstance(detail, str) else '见 JSON'))
    print('RESULT:', 'PASS' if report['ok'] else 'FAIL')
    return 0 if report['ok'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
